#!/usr/bin/env bash
# Starts the CMIS test stack in a GitHub Codespace (runs automatically on every start).
# First start: writes .env with random secrets, builds, loads demo data and creates a test login.
set -euo pipefail
cd "$(dirname "$0")/.."
LOGIN_FILE=.devcontainer/test-login.txt

if [ -n "${CODESPACE_NAME:-}" ]; then
  APP_URL="https://${CODESPACE_NAME}-80.${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN:-app.github.dev}"
  HOSTS="localhost,127.0.0.1,.${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN:-app.github.dev}"
else
  APP_URL="http://localhost"
  HOSTS="localhost,127.0.0.1"
fi

if [ ! -f .env ]; then
  rand() { python3 -c "import secrets; print(secrets.token_urlsafe($1))"; }
  cat > .env <<ENV
# Generated by .devcontainer/start.sh for a TEST codespace. Not for real church records.
DJANGO_SETTINGS_MODULE=config.settings.trial
DJANGO_SECRET_KEY=$(rand 64)
DJANGO_ALLOWED_HOSTS=${HOSTS}
CSRF_TRUSTED_ORIGINS=${APP_URL}
FRONTEND_URL=${APP_URL}
CMIS_DOMAIN=:80
SECURE_SSL_REDIRECT=false
POSTGRES_DB=cmis
POSTGRES_USER=cmis
POSTGRES_PASSWORD=$(rand 24)
POSTGRES_HOST=db
EMAIL_BACKEND=django.core.mail.backends.console.EmailBackend
BACKUP_KEEP_DAYS=7
ENV
  chmod 600 .env
fi
mkdir -p backups

echo "Starting the CMIS test stack (the first start builds images and takes a few minutes)..."
docker compose up -d --build

echo "Waiting for the API..."
for _ in $(seq 1 90); do
  if docker compose exec -T api python -c "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/api/health/')" >/dev/null 2>&1; then
    break
  fi
  sleep 2
done

if [ ! -f "$LOGIN_FILE" ]; then
  echo "Loading demo data (made-up members, money and assets, marked as demo records)..."
  docker compose exec -T api python manage.py seed_demo
  PASSWORD="Test-$(python3 -c "import secrets; print(secrets.token_urlsafe(12))")"
  docker compose exec -T -e ADMIN_PASSWORD="$PASSWORD" api python manage.py provision_admin \
    --role system_admin --username testadmin --email testadmin@example.org \
    --full-name "Test Administrator" --password-env ADMIN_PASSWORD --no-force-change
  umask 077
  printf 'Address:  %s\nUsername: testadmin\nPassword: %s\n' "$APP_URL" "$PASSWORD" > "$LOGIN_FILE"
fi

echo
echo "================ CMIS test system is running ================"
cat "$LOGIN_FILE"
echo "(This login is saved in $LOGIN_FILE in this codespace only.)"
echo "=============================================================="
